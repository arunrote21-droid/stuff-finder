/* ---------------- matching ---------------- */
const norm = s => String(s || '').toLowerCase().replace(/[\s_\-.,()/]+/g, '');
const index = list.map(e => ({ e, keys: e.k.map(norm).filter(Boolean) }));
// best entry for what the user typed: exact > longest key contained in the text > text contained in a key
function match(text, limit = 1) {
  const t = norm(text); if (!t) return limit === 1 ? null : [];
  const scored = [];
  for (const { e, keys } of index) {
    let best = 0;
    for (const k of keys) {
      if (k === t) best = Math.max(best, 1000 + k.length + (k === keys[0] ? 50 : 0)); // the entry's own name beats a mere alias
      else if (t.includes(k)) best = Math.max(best, 100 + k.length);
      else if (k.includes(t) && t.length >= 2) best = Math.max(best, 40 + t.length);
    }
    if (best) scored.push([best, e]);
  }
  scored.sort((a, b) => b[0] - a[0]);
  return limit === 1 ? (scored[0] ? scored[0][1] : null) : scored.slice(0, limit).map(x => x[1]);
}

